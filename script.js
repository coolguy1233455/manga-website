function renderMangaCards() {
  const grid = document.querySelector("#mangaGrid");

  if (!grid) return;

  grid.innerHTML = mangaLibrary
    .map(
      (manga) => `
        <article class="manga-card" data-manga-id="${manga.id}" tabindex="0">
          <img src="${manga.cover}" alt="${manga.title} cover" />
          <div class="manga-body">
            <div class="manga-header">
              <h3>${manga.title}</h3>
              <span class="manga-badge">${manga.badge}</span>
            </div>
            <p>${manga.description}</p>
            <div class="manga-meta">
              <span>Vol. ${manga.chapters.length}</span>
              <span>★ 4.9</span>
            </div>
          </div>
        </article>
      `
    )
    .join("");

  grid.querySelectorAll(".manga-card").forEach((card) => {
    card.addEventListener("click", () => {
      const id = card.dataset.mangaId;
      const manga = mangaLibrary.find((item) => item.id === id);
      if (!manga) return;

      window.location.href = `reader.html?manga=${encodeURIComponent(manga.id)}&chapter=1`;
    });
  });
}

function getMangaFromQuery() {
  const params = new URLSearchParams(window.location.search);
  const mangaId = params.get("manga");
  const chapterNumber = Number(params.get("chapter") || 1);
  const manga = mangaLibrary.find((item) => item.id === mangaId) || mangaLibrary[0];
  const chapter =
    manga.chapters.find((item) => item.number === chapterNumber) || manga.chapters[0];

  return { manga, chapter, chapterNumber };
}

function renderReader() {
  const page = document.querySelector("#readerPages");
  const titleEl = document.querySelector("#readerTitle");
  const chapterHeading = document.querySelector("#chapterHeading");
  const chapterCount = document.querySelector("#chapterCount");
  const chapterList = document.querySelector("#chapterList");
  const sidebarCover = document.querySelector("#mangaSidebarCover");
  const prevBtn = document.querySelector("#prevChapterBtn");
  const nextBtn = document.querySelector("#nextChapterBtn");

  if (!page || !titleEl || !chapterHeading || !chapterList || !sidebarCover) return;

  const { manga, chapter, chapterNumber } = getMangaFromQuery();

  titleEl.textContent = manga.title;
  chapterHeading.textContent = `Chapter ${chapter.number}: ${chapter.title}`;
  chapterCount.textContent = `${manga.chapters.length}`;
  sidebarCover.style.backgroundImage = `url(${manga.cover})`;

  chapterList.innerHTML = manga.chapters
    .map(
      (item) => `
        <button class="chapter-item ${item.number === chapter.number ? "active" : ""}" data-chapter="${item.number}">
          <strong>Chapter ${item.number}</strong>
          <small>${item.title}</small>
        </button>
      `
    )
    .join("");

  chapterList.querySelectorAll(".chapter-item").forEach((button) => {
    button.addEventListener("click", () => {
      const selectedChapter = Number(button.dataset.chapter);
      window.location.href = `reader.html?manga=${encodeURIComponent(manga.id)}&chapter=${selectedChapter}`;
    });
  });

  page.innerHTML = chapter.pages
    .map(
      (image) => `
        <div class="manga-page">
          <img src="${image}" alt="${manga.title} chapter ${chapter.number}" />
        </div>
      `
    )
    .join("");

  const hasPrevChapter = chapterNumber > 1;
  const hasNextChapter = chapterNumber < manga.chapters.length;

  prevBtn.disabled = !hasPrevChapter;
  nextBtn.disabled = !hasNextChapter;
  prevBtn.style.opacity = hasPrevChapter ? "1" : "0.5";
  nextBtn.style.opacity = hasNextChapter ? "1" : "0.5";

  prevBtn.addEventListener("click", () => {
    const previousChapter = Math.max(1, chapterNumber - 1);
    window.location.href = `reader.html?manga=${encodeURIComponent(manga.id)}&chapter=${previousChapter}`;
  });

  nextBtn.addEventListener("click", () => {
    const nextChapter = Math.min(manga.chapters.length, chapterNumber + 1);
    window.location.href = `reader.html?manga=${encodeURIComponent(manga.id)}&chapter=${nextChapter}`;
  });
}

if (document.querySelector("#mangaGrid")) {
  renderMangaCards();
}

if (document.querySelector("#readerPages")) {
  renderReader();
}
